# --- 3.5 القيم الشاذة بطريقة IQR على عمود الكمية ---
def اكتشف_الشواذ_iqr(البيانات, العمود):
    الربيع_الأول = البيانات[العمود].quantile(0.25)      # Q1
    الربيع_الثالث = البيانات[العمود].quantile(0.75)     # Q3
    المدى_الربيعي = الربيع_الثالث - الربيع_الأول          # IQR = Q3 - Q1
    الحد_الأدنى = الربيع_الأول - 1.5 * المدى_الربيعي
    الحد_الأعلى = الربيع_الثالث + 1.5 * المدى_الربيعي
    الشاذة = البيانات[(البيانات[العمود] < الحد_الأدنى) | (البيانات[العمود] > الحد_الأعلى)]
    return الشاذة, الحد_الأدنى, الحد_الأعلى


