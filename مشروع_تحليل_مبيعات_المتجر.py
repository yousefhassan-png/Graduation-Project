print(f'بدون خصم  : عدد = {len(كمية_بدون_خصم)} ، متوسط الكمية = {كمية_بدون_خصم.mean():.2f}')

# equal_var=False يعني اختبار Welch وهو آمن عندما يختلف حجم المجموعتين
قيمة_t, قيمة_p = stats.ttest_ind(كمية_مع_خصم, كمية_بدون_خصم, equal_var=False)
print()
print(f'قيمة t = {قيمة_t:.3f}')
print(f'قيمة p-value = {قيمة_p:.4f}')

if قيمة_p < 0.05:
    print('النتيجة: دال إحصائياً (p < 0.05) -> نرفض H0، يوجد فرق حقيقي في متوسط الكمية.')
else:
    print('النتيجة: غير دال إحصائياً (p >= 0.05) -> لا نستطيع رفض H0، الفرق الظاهر قد يكون صدفة.')

print(f'''التفسير: الفرق في المتوسطات صغير ({كمية_مع_خصم.mean() - كمية_بدون_خصم.mean():+.2f} قطعة) وقيمة p = {قيمة_p:.2f}
أكبر بكثير من 0.05، أي أنه لا يوجد دليل على أن الخصم يرفع الكمية المباعة. بما أن الخصم يقلّل
الإيراد، فالتوصية: مراجعة سياسة الخصومات. (ملاحظة: الاختبار صالح لأن حجم العينة كبير،
رغم أن الكمية ملتوية قليلاً).''')


